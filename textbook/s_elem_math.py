def gear(cx, cy, r, n, col):
    import math as m
    pts = []
    for k in range(n*2):
        a = m.pi*k/n; rr = r if k % 2 == 0 else r*.86
        pts.append(f"{cx+rr*m.cos(a):.1f},{cy+rr*m.sin(a):.1f}")
    return f'<polygon points="{" ".join(pts)}" fill="{col}" stroke="#1b1f24" stroke-width="1.4"/><circle cx="{cx}" cy="{cy}" r="{r*.22}" fill="#fff" stroke="#1b1f24"/>'
